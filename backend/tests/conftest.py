def _make_video(path, *, with_audio: bool, seconds: int = 3):
    ffmpeg = shutil.which(get_settings().ffmpeg_path)
    if ffmpeg is None:
        pytest.skip("FFmpeg not available")
    args = [ffmpeg, "-hide_banner", "-loglevel", "error", "-y",
            "-f", "lavfi", "-i", f"testsrc2=size=320x240:rate=25:duration={seconds}"]
    if with_audio:
        args += ["-f", "lavfi", "-i", f"sine=frequency=440:duration={seconds}", "-c:a", "aac"]
    args += ["-c:v", "libx264", "-pix_fmt", "yuv420p", "-shortest", str(path)]
    subprocess.run(args, check=True, timeout=120)
    return path


